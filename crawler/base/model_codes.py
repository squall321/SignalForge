# 세대는 확실하나 모델이 미확정(출시 전) — 질의 범위만. PLM 개발모델이 들어오면 EXACT 로 옮긴다.
_FAMILY_SRC: Dict[Tuple[str, ...], Tuple[str, ...]] = {
    ("GS27", "GS27P", "GS27U"): ("S952", "S956", "S957", "S958"),
}


def _invert() -> Tuple[Dict[str, str], Dict[str, Tuple[str, ...]]]:
    exact: Dict[str, str] = {}
    for product, bases in _BY_PRODUCT.items():
        for b in bases:
            if b in exact and exact[b] != product:
                raise ValueError(f"모델코드 {b} 가 두 제품({exact[b]}, {product})에 걸렸다")
            exact[b] = product
    family: Dict[str, Tuple[str, ...]] = {}
    for products, bases in _FAMILY_SRC.items():
        for b in bases:
            if b in exact:
                raise ValueError(f"모델코드 {b} 가 EXACT 와 FAMILY 에 다 있다")
            family[b] = products
    return exact, family


EXACT, FAMILY = _invert()

# 'SM-S938B' · 'sm-s938b/ds' · 'SMS938' · 'SM-S9380' · 'SM-S938BZKDEUB'(색상·지역 SKU). 앞뒤가 영숫자면 안 된다.
_CODE_RE = re.compile(r"(?<![0-9a-z])sm-?([a-z])([0-9]{3})([0-9a-z]{0,8})(?![0-9a-z])", re.IGNORECASE)


def base_of(text: str) -> Optional[str]:
    """모델코드 하나(또는 개발모델명 'SM-X100A_KOR_SKT')의 기본 코드. 모델코드가 아니면 None."""
    m = _CODE_RE.search(text or "")
    return (m.group(1) + m.group(2)).upper() if m else None


def iter_codes(text: str) -> Iterator[Tuple[str, str, int, int]]:
    """본문·질의 속 모델코드 → (원문, 기본 코드, 시작, 끝)."""
    for m in _CODE_RE.finditer(text or ""):
        yield m.group(0), (m.group(1) + m.group(2)).upper(), m.start(), m.end()


def product_of(base: str) -> Optional[str]:
    return EXACT.get((base or "").upper())


def family_of(base: str) -> Tuple[str, ...]:
    b = (base or "").upper()
    return (EXACT[b],) if b in EXACT else FAMILY.get(b, ())


def exact_products(text: str) -> List[Tuple[str, Tuple[int, int]]]:
    """본문에서 EXACT 로 잇는 제품과 그 구간(처음 나온 차례, 중복 없음) — 태깅 길목이 쓴다."""
    out: List[Tuple[str, Tuple[int, int]]] = []
    for _raw, base, s, e in iter_codes(text):
        p = EXACT.get(base)
        if p and all(p != q for q, _ in out):
            out.append((p, (s, e)))
    return out
