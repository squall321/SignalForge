#!/usr/bin/env bash
# PG_SHARED_BUFFERS(opt-in) 의 값 변환·postgresql.auto.conf 쓰기·되돌리기를 고정하는 테스트
#   T1. pg_size_bytes: kB·MB·GB 변환, 그 밖의 형식 거부
#   T2. 비움 → 아무것도 안 씀(dev)
#   T3. 첫 쓰기 → 한 줄 추가 + .sf-bak + rc 0, 다른 설정 보존
#   T4. 같은 값 → rc 1(다시 띄울 일 없음), 파일 그대로
#   T5. 다른 값 → 한 줄로 교체
#   T6. 형식 오류 → rc 1, 파일 그대로
#   T7. 메모리 40% 초과 → rc 1, 파일 그대로
#   T8. (SF_PG_IT=1 일 때만) 임시 postgres 인스턴스 — 쓴 값으로 실제로 뜨는지, 안 뜨는 값이면
#       postmaster 가 남지 않는지(up.sh 의 되돌리기 조건), .sf-bak 로 되돌리면 다시 뜨는지.
#       운영 DB·인스턴스는 건드리지 않는다.
#   T9. (SF_PG_IT=1) up.sh 의 postgres 구간을 그대로 임시 인스턴스로 — 새 DB 는 알림, 다시 띄우면
#       적용·.sf-bak 정리, 바꾼 실행이 끊겨 .sf-bak 만 남은 변경은 다음 실행이 되돌린다.
#   T10. (SF_PG_IT=1) 같은 구간의 PG_FRESH(새 pgdata — seed) · PG_STARTED(이 실행이 띄웠나) 판정.
set -uo pipefail
PASS=0; FAIL=0
TESTS_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
SCRIPTS_DIR="$(cd "$TESTS_DIR/.." && pwd)"

pass() { echo "  [PASS] $*"; PASS=$((PASS+1)); }
fail() { echo "  [FAIL] $*" >&2; FAIL=$((FAIL+1)); }

# shellcheck source=../_common.sh
source "$SCRIPTS_DIR/_common.sh"

TMP="$(mktemp -d)"
trap 'rm -rf "$TMP"' EXIT
CONF="$TMP/postgresql.auto.conf"
cat > "$CONF" <<'EOF'
# Do not edit this file manually!
# It will be overwritten by the ALTER SYSTEM command.
work_mem = '8MB'
EOF
sum() { sha256sum "$CONF" | awk '{print $1}'; }

echo "================================================================"
echo " PG_SHARED_BUFFERS — 변환·쓰기·되돌리기"
echo "================================================================"

echo "[T1] pg_size_bytes"
[[ "$(pg_size_bytes 2GB)" == 2147483648 ]] && pass "2GB" || fail "2GB → $(pg_size_bytes 2GB)"
[[ "$(pg_size_bytes 512MB)" == 536870912 ]] && pass "512MB" || fail "512MB"
[[ "$(pg_size_bytes 1024kB)" == 1048576 ]] && pass "1024kB" || fail "1024kB"
for bad in 2G 2gb 2.5GB "" GB "2 GB" 2TB; do
  if pg_size_bytes "$bad" >/dev/null; then fail "'$bad' 를 받았다"; else pass "'$bad' 거부"; fi
done

echo "[T2] 비움 → 그대로"
before=$(sum)
if pg_write_shared_buffers "$CONF" ""; then fail "빈 값에 rc 0"; else pass "rc 1"; fi
[[ "$(sum)" == "$before" ]] && pass "파일 그대로" || fail "파일이 바뀌었다"

echo "[T3] 첫 쓰기"
cp "$CONF" "$TMP/orig"
if pg_write_shared_buffers "$CONF" 256MB; then pass "rc 0"; else fail "rc 1"; fi
[[ "$(grep -c '^shared_buffers' "$CONF")" == 1 ]] && pass "shared_buffers 한 줄" || fail "줄 수 $(grep -c '^shared_buffers' "$CONF")"
grep -qxF "shared_buffers = '256MB'" "$CONF" && pass "ALTER SYSTEM 형식" || fail "형식: $(grep '^shared_buffers' "$CONF")"
grep -qxF "work_mem = '8MB'" "$CONF" && pass "다른 설정 보존" || fail "work_mem 사라짐"
cmp -s "$CONF.sf-bak" "$TMP/orig" && pass ".sf-bak = 원본" || fail ".sf-bak 이 원본이 아니다"

echo "[T4] 같은 값 → 다시 띄울 일 없음"
before=$(sum)
if pg_write_shared_buffers "$CONF" 256MB; then fail "같은 값에 rc 0"; else pass "rc 1"; fi
[[ "$(sum)" == "$before" ]] && pass "파일 그대로" || fail "파일이 바뀌었다"

echo "[T5] 다른 값 → 교체"
if pg_write_shared_buffers "$CONF" 512MB; then pass "rc 0"; else fail "rc 1"; fi
[[ "$(grep -c '^shared_buffers' "$CONF")" == 1 ]] && grep -qxF "shared_buffers = '512MB'" "$CONF" \
  && pass "한 줄로 교체" || fail "$(grep '^shared_buffers' "$CONF" | tr '\n' '|')"

echo "[T6] 형식 오류"
before=$(sum)
if pg_write_shared_buffers "$CONF" 2G 2>/dev/null; then fail "'2G' 에 rc 0"; else pass "rc 1"; fi
[[ "$(sum)" == "$before" ]] && pass "파일 그대로" || fail "파일이 바뀌었다"

echo "[T7] 메모리 40% 초과"
mem_gb=$(( $(awk '/^MemTotal:/ {print $2}' /proc/meminfo) / 1048576 ))
big="$(( mem_gb / 2 + 1 ))GB"
before=$(sum)
if pg_write_shared_buffers "$CONF" "$big" 2>/dev/null; then fail "$big 에 rc 0"; else pass "$big 거부(메모리 ${mem_gb}GB)"; fi
[[ "$(sum)" == "$before" ]] && pass "파일 그대로" || fail "파일이 바뀌었다"

if [[ "${SF_PG_IT:-0}" == 1 ]]; then
  echo "[T8] 임시 postgres 인스턴스 (운영과 별개 데이터·포트)"
  SIF="$APPT_DIR/sif/postgres.sif"
  INST="sf_pgtest_$$"
  PORT=$(( 55400 + $$ % 100 ))
  D="$TMP/pg"; mkdir -p "$D/data" "$D/run"
  it_start() {
    apptainer instance start --bind "$D/data:/var/lib/postgresql/data" --bind "$D/run:/var/run/postgresql" \
      --env POSTGRES_USER=t --env POSTGRES_PASSWORD=t --env POSTGRES_DB=t --env "PGPORT=$PORT" \
      --env PGDATA=/var/lib/postgresql/data/pgdata --env LANG=C.UTF-8 --env LC_ALL=C.UTF-8 \
      "$SIF" "$INST" >/dev/null 2>&1
  }
  it_ready() {  # $1=기다릴 초
    local i
    for i in $(seq 1 "$1"); do
      apptainer exec "instance://$INST" pg_isready -h 127.0.0.1 -p "$PORT" -U t >/dev/null 2>&1 && return 0
      sleep 1
    done
    return 1
  }
  it_sb() {
    apptainer exec --env PGPASSWORD=t "instance://$INST" psql -h 127.0.0.1 -p "$PORT" -U t -d t -tAc \
      "SHOW shared_buffers" 2>/dev/null
  }
  it_stop() { apptainer instance stop "$INST" >/dev/null 2>&1 || true; }
  trap 'it_stop; rm -rf "$TMP"' EXIT
  ITCONF="$D/data/pgdata/postgresql.auto.conf"

  if [[ ! -f "$SIF" ]]; then
    fail "postgres.sif 없음"
  elif it_start && it_ready 90; then
    pass "첫 기동(initdb) — shared_buffers $(it_sb)"
    it_stop
    if pg_write_shared_buffers "$ITCONF" 256MB && it_start && it_ready 60 && [[ "$(it_sb)" == 256MB ]]; then
      pass "쓴 값으로 뜬다 — SHOW shared_buffers = 256MB"
    else
      fail "256MB 로 뜨지 않았다 — $(it_sb)"
    fi
    it_stop
    # 형식은 맞지만 서버가 거부하는 값(최소 128kB) — up.sh 의 되돌리기 경로와 같은 순서로 복구
    pg_write_shared_buffers "$ITCONF" 1kB
    if it_start && it_ready 15; then
      fail "1kB 로 떴다 — 실패 경로를 시험하지 못했다"
    else
      pass "1kB 로는 안 뜬다"
      # up.sh 는 postmaster 가 죽었을 때만 되돌린다(복구 중인 서버는 기다린다) — 그 판정이 맞는지
      pmpid="$(head -n1 "$D/data/pgdata/postmaster.pid" 2>/dev/null | tr -dc '0-9' || true)"
      if [[ -n "$pmpid" ]] && kill -0 "$pmpid" 2>/dev/null; then
        fail "실패한 기동인데 postmaster($pmpid)가 살아 있다 — up.sh 가 되돌리지 못한다"
      else
        pass "실패한 기동 뒤 postmaster 없음 — up.sh 의 되돌리기 조건이 선다"
      fi
      it_stop
      mv -f "$ITCONF.sf-bak" "$ITCONF"
      if it_start && it_ready 60 && [[ "$(it_sb)" == 256MB ]]; then
        pass ".sf-bak 로 되돌리면 다시 뜬다 — 256MB"
      else
        fail "되돌린 뒤 안 뜬다 — $(it_sb)"
      fi
    fi
    it_stop
  else
    fail "임시 인스턴스가 뜨지 않았다"
    it_stop
  fi

  echo "[T9] up.sh 의 postgres 구간 그대로 — 새 DB·적용·끊긴 변경 되돌리기"
  SECTION="$TMP/pg_section.sh"
  sed -n '/^# >>> postgres/,/^# <<< postgres/p' "$SCRIPTS_DIR/up.sh" > "$SECTION"
  INST2="sf_pgtest2_$$"
  PORT2=$(( 55500 + $$ % 100 ))
  D2="$TMP/pg2"; mkdir -p "$D2/postgres" "$D2/postgres-run"
  CONF2="$D2/postgres/pgdata/postgresql.auto.conf"
  up_pg() {  # $1=PG_SHARED_BUFFERS — up.sh 와 같은 셸 옵션으로 구간을 돌린다
    ( set -euo pipefail
      DATA_DIR="$D2"; LOG_DIR="$TMP"; SIF_DIR="$APPT_DIR/sif"; INST_POSTGRES="$INST2"
      POSTGRES_PORT="$PORT2"; POSTGRES_USER=t; POSTGRES_PASSWORD=t; POSTGRES_DB=t; PG_SHARED_BUFFERS="$1"
      # shellcheck source=/dev/null
      source "$SECTION" ) 2>&1
  }
  sb2() {
    apptainer exec --env PGPASSWORD=t "instance://$INST2" psql -h 127.0.0.1 -p "$PORT2" -U t -d t -tAc \
      "SHOW shared_buffers" 2>/dev/null
  }
  stop2() { apptainer instance stop "$INST2" >/dev/null 2>&1 || true; }
  trap 'it_stop; stop2; rm -rf "$TMP"' EXIT

  if ! grep -q "^pg_instance_start() {" "$SECTION"; then
    fail "up.sh 에서 '# >>> postgres' ~ '# <<< postgres' 구간을 못 찾았다"
  else
    out=$(up_pg 256MB)
    if [[ "$(sb2)" == 128MB ]] && grep -q "NOTE" <<<"$out"; then
      pass "새 DB — initdb 전이라 128MB 로 뜨고 [NOTE] 로 알린다"
    else
      fail "새 DB: $(sb2) / $(tail -2 <<<"$out")"
    fi
    stop2
    out=$(up_pg 256MB)
    if [[ "$(sb2)" == 256MB && ! -e "$CONF2.sf-bak" ]]; then
      pass "다시 띄우면 256MB, 뜬 뒤 .sf-bak 정리"
    else
      fail "적용: $(sb2) / .sf-bak $([[ -e "$CONF2.sf-bak" ]] && echo 남음) / $(tail -2 <<<"$out")"
    fi
    stop2
    # 1kB 를 쓴 실행이 띄우기 전에 끊겼다고 친다(.sf-bak 만 남음) — 다음 실행(워치독)이 되돌려야 한다
    pg_write_shared_buffers "$CONF2" 1kB
    out=$(up_pg 1kB)
    if [[ "$(sb2)" == 256MB && ! -e "$CONF2.sf-bak" ]] && grep -q "원래 설정으로 되돌려" <<<"$out"; then
      pass "끊긴 변경을 다음 실행이 되돌린다 — 256MB 로 다시 떴다"
    else
      fail "되돌리지 못했다: $(sb2) / $(tail -3 <<<"$out")"
    fi
    stop2

    echo "[T10] PG_FRESH 는 'pgdata 를 새로 만드는가' — 있는 pgdata 를 다시 띄우면 seed 를 안 돈다(SG-14)"
    flags() {  # 구간을 돌린 뒤 두 판정을 찍는다 — $1=데이터 디렉터리
      ( set -euo pipefail
        DATA_DIR="$1"; LOG_DIR="$TMP"; SIF_DIR="$APPT_DIR/sif"; INST_POSTGRES="$INST2"
        POSTGRES_PORT="$PORT2"; POSTGRES_USER=t; POSTGRES_PASSWORD=t; POSTGRES_DB=t; PG_SHARED_BUFFERS=""
        # shellcheck source=/dev/null
        source "$SECTION" >/dev/null; echo "FLAGS fresh=$PG_FRESH started=$PG_STARTED" ) 2>&1 | grep '^FLAGS'
    }
    f1=$(flags "$D2")                 # 있는 pgdata · 꺼진 인스턴스 — 띄우지만 새로 만들지 않는다
    f2=$(flags "$D2")                 # 떠 있다 — 아무것도 안 한다
    stop2
    D3="$TMP/pg3"; mkdir -p "$D3/postgres" "$D3/postgres-run"
    f3=$(flags "$D3")                 # 빈 디렉터리 — initdb
    stop2
    if [[ "$f1|$f2|$f3" == "FLAGS fresh=0 started=1|FLAGS fresh=0 started=0|FLAGS fresh=1 started=1" ]]; then
      pass "있는 pgdata 재기동 fresh=0 · 떠 있음 started=0 · 빈 디렉터리 fresh=1"
    else
      fail "판정: $f1 / $f2 / $f3"
    fi
  fi
else
  echo "[T8·T9] 건너뜀 — 임시 postgres 로 실제 기동까지 보려면 SF_PG_IT=1"
fi

echo
echo "================================================================"
echo " 결과: PASS=$PASS  FAIL=$FAIL"
echo "================================================================"
[[ $FAIL -eq 0 ]] && exit 0 || exit 1
